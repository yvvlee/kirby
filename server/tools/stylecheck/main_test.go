package main

import (
	"go/token"
	"testing"
)

func TestProductionRules(t *testing.T) {
	tests := []struct {
		name   string
		source string
		rule   string
	}{
		{
			name:   "grouped parameters still count individually",
			source: "package sample; func update(a,b,c,d,e,f int) {}",
			rule:   "argscount",
		},
		{
			name:   "constructor dependencies are exempt",
			source: "package sample\n// NewStore wires dependencies.\n// Parameters: a through f are dependencies.\n// Returns: none.\n// Throws: none.\nfunc NewStore(a,b,c,d,e,f int) {}",
		},
		{
			name:   "interface scope is explicit",
			source: "package sample; type lookup interface { Get(int64, int64) error }",
			rule:   "namedparams",
		},
		{
			name:   "nested branches need extraction",
			source: "package sample; func run() { for { if true { if false {} } } }",
			rule:   "nesting",
		},
		{
			name:   "else if does not add a level",
			source: "package sample; func run() { for { if true {} else if false {} } }",
		},
		{
			name:   "fields need separate lines",
			source: "package sample; var value = thing{first: 1, second: 2}",
			rule:   "fieldlines",
		},
		{
			name:   "structured log pairs",
			source: `package sample; func run() { logger.Errorw("msg", "failed", "error") }`,
			rule:   "mustlogpair",
		},
		{
			name:   "expanded logs are checked by their producer",
			source: "package sample; func run() { logger.Errorw(fields...) }",
		},
		{
			name:   "log level is separate from fields",
			source: `package sample; func run() { logger.Log(level, "msg", "failed", "error") }`,
			rule:   "mustlogpair",
		},
		{
			name:   "grouped struct declarations need separate fields",
			source: "package sample; type entry struct { key, value string }",
			rule:   "fieldlines",
		},
		{
			name:   "explicit constants",
			source: "package sample; const value = iota",
			rule:   "noiota",
		},
		{
			name:   "exported operations document their contract",
			source: "package sample; func Read() {}",
			rule:   "docstring",
		},
		{
			name:   "generated source is not edited by hand",
			source: "// Code generated by an external tool. DO NOT EDIT.\npackage sample; func Read(a,b,c,d,e,f int) {}",
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			check := &checker{files: token.NewFileSet()}
			if err := check.file("sample.go", test.source); err != nil {
				t.Fatal(err)
			}
			if test.rule == "" && len(check.diagnostics) != 0 {
				t.Fatalf("unexpected diagnostics: %v", check.diagnostics)
			}
			for _, finding := range check.diagnostics {
				if finding.rule == test.rule {
					return
				}
			}
			if test.rule != "" {
				t.Fatalf("missing %s diagnostic", test.rule)
			}
		})
	}
}
